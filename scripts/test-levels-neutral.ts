/**
 * Названия уровней не оценивают ребёнка.
 *
 * Уровень видит сам ребёнок в верхней панели и взрослый в отчёте. Значит,
 * название уровня — это фраза о ребёнке, а не только ярлык прогресса. Прежний
 * набор («Умница», «Знаток», «Стратег», «Легенда района») приписывал ребёнку
 * свойство за набранный опыт, и это противоречит правилу «не рейтинговать
 * детей»: ребёнок читает про себя оценку, которую нельзя оспорить.
 *
 * Проверяем:
 * 1. шкала осталась прежней (minXp/next), чтобы старые снимки читались как
 *    раньше, — меняются только формулировки;
 * 2. ни одно название не содержит слов-оценок и сравнений;
 * 3. названия различны и непусты, а `levelOf` по-прежнему монотонен.
 */
import assert from 'node:assert/strict';
import { LEVELS, levelOf } from '../lib/gamification.ts';
import { petStage } from '../lib/pet-mood.ts';

/* ---- 1. Шкала не тронута ---- */
{
  // Если кто-то захочет «поправить» шкалу вместе с названиями, пусть это
  // будет осознанное решение: тест держит числа, а не только слова.
  const mins = LEVELS.map(l => l.minXp);
  assert.deepEqual(mins, [0, 60, 140, 260, 420, 640, 920, 1400], 'границы опыта прежние');
  assert.equal(LEVELS.length, 8, 'уровней восемь');
  console.log('  ok шкала опыта прежняя: 8 уровней, те же границы');
}

/* ---- 2. В названиях нет оценки ребёнка ---- */
{
  // Слова, которыми называют не место в программе, а самого ребёнка.
  const RATING = /умниц|умник|молодец|знаток|стратег|легенд|мастер|гений|талант|отличник|лучш|звезд|звёзд|элитн|профи|эксперт|чемпион/i;
  const bad = LEVELS.filter(l => RATING.test(l.title));
  assert.deepEqual(bad.map(l => `${l.level}: ${l.title}`), [], 'названия уровней не оценивают ребёнка');

  // Сравнение с другими — тоже оценка.
  const COMPARE = /лучше|хуже|других|среди|рейтинг|место в/i;
  const comparing = LEVELS.filter(l => COMPARE.test(l.title));
  assert.deepEqual(comparing.map(l => l.title), [], 'нет сравнения с другими детьми');
  console.log('  ok в названиях уровней нет оценок, званий и сравнений');
}

/* ---- 3. Названия рабочие ---- */
{
  const titles = LEVELS.map(l => l.title);
  assert.equal(new Set(titles).size, titles.length, 'названия не повторяются');
  for (const title of titles) {
    assert.ok(title.trim().length > 0, 'название не пустое');
    assert.ok(title.length <= 24, `название помещается в панель: «${title}» (${title.length})`);
  }
  console.log('  ok названия уровней различны, непусты и помещаются в панель');
}

/* ---- 4. Уровень считается как раньше ---- */
{
  // Названия поменялись, поведение — нет: старые снимки дают тот же уровень.
  const pairs: [number, number][] = [[0, 1], [59, 1], [60, 2], [260, 4], [920, 7], [5000, 8]];
  for (const [xp, level] of pairs) assert.equal(levelOf(xp).level, level, `xp=${xp} → уровень ${level}`);

  // Мусор не поднимает ребёнка выше первого уровня.
  assert.equal(levelOf(Number.NaN).level, 1, 'NaN → первый уровень');
  assert.equal(levelOf(-100).level, 1, 'отрицательный опыт → первый уровень');
  console.log('  ok уровень считается по прежней шкале, мусор не поднимает его');
}

/* ---- 5. Питомец по-прежнему растёт по уровню, а не по оценке ---- */
{
  // Порог стадий питомца привязан к уровню, а не к «успешности»; связь
  // проверяется здесь, чтобы смена названий не сломала рост питомца.
  assert.equal(petStage(levelOf(0).level), 0);
  assert.equal(petStage(levelOf(60).level), 0);
  assert.equal(petStage(levelOf(140).level), 1);
  assert.equal(petStage(levelOf(920).level), 2);
  console.log('  ok стадии питомца считаются от уровня и не зависят от названий');
}

console.log('\nНазвания уровней: ступени пути, а не оценки ребёнка.');
