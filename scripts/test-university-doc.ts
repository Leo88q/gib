/**
 * Документ для ректора: числа должны сходиться с кодом.
 *
 * Зачем проверка документа тестом. Это единственный документ в проекте, который
 * читает человек, принимающий решение о партнёрстве, и он читает его один раз.
 * Ошибка в числе здесь стоит дороже, чем ошибка в коде: код проверят тесты, а
 * документ — нет. Поэтому числа в документе сверяются с репозиторием, а
 * запрещённые обещания — с решениями, записанными в коде.
 *
 * Проверяется:
 *  1. Числа программы совпадают с кодом: 36 занятий, 60 дней, 54 навыка, 39 в
 *     конструктах, 12 показов, три возрастные линейки.
 *  2. Число тестов и файлов совпадает с фактическим.
 *  3. В документе нет обещаний, которых продукт не выполняет: роста IQ, оценки
 *     социального выбора, рейтингов детей.
 *  4. Расчёт выборки внутренне согласован: 5 классов → 250 детей → d 0.65.
 *  5. Каждый блокер из раздела 8 действительно назван, а не спрятан.
 *
 * Запуск: npm run test-university-doc
 */

import { strict as assert } from 'node:assert';
import { readFileSync, readdirSync } from 'node:fs';
import { YEAR } from '../lib/content/year/index.ts';
import { SKILLS_CATALOG } from '../lib/content/skills-catalog.ts';
import { PROGRAM_DAYS } from '../lib/content/program/index.ts';

const doc = readFileSync(new URL('../docs/university-partnership.md', import.meta.url), 'utf8');

/* ---- 1. Числа программы ---- */

assert.equal(YEAR.lessons.length, 36, `в коде ${YEAR.lessons.length} занятий, документ говорит 36`);
assert.ok(/36 занятий/.test(doc), 'в документе нет числа занятий');

assert.equal(PROGRAM_DAYS.length, 60, `в коде ${PROGRAM_DAYS.length} дней, документ говорит 60`);
assert.ok(/60 сцен|60 коротких сцен/.test(doc), 'в документе нет числа дней симулятора');

assert.equal(SKILLS_CATALOG.length, 54, `в каталоге ${SKILLS_CATALOG.length} навыков, документ говорит 54`);
assert.ok(/из них 39 \(72%\)/.test(doc), 'разметка навыков в документе не совпадает с картой конструктов');

assert.equal(YEAR.lessons.filter((lesson) => lesson.isShowcase).length, 12, 'показов не 12');
assert.ok(/12 показов/.test(doc), 'в документе нет числа показов');

/* ---- Метод: актёрское мастерство, а не «уроки про эмоции» ---- */

// Это направление продукта, а не контекст: если слово исчезнет из документа,
// ректор прочитает описание тренажёра, а не курса.
// `\w` в JavaScript — только ASCII: /актёрск\w+ мастерств/ не находит
// «актёрское мастерство». Для кириллицы нужен явный диапазон. Это второй
// случай за сессию (первый — \b в проверке на отрицание), и он записан в docs.
assert.ok(/актёрск[а-яё]+ мастерств/i.test(doc), 'в документе не назван метод — актёрское мастерство');
assert.ok(/12 показов|двенадцать/i.test(doc), 'в документе нет показов как части метода');

// Шкала показа — центральный результат актёрской методики. Она должна быть
// описана теми же словами, что в коде, иначе бланк и продукт разойдутся.
assert.ok(/отказался после двух приглашений/i.test(doc), 'в документе нет якоря 0 шкалы показа');
assert.ok(/вышел после приглашения/i.test(doc), 'в документе нет якоря 1 шкалы показа');
assert.ok(/вышел сам/i.test(doc), 'в документе нет якоря 2 шкалы показа');
console.log('  ok метод назван, шкала показа описана теми же словами, что в коде');

// Три возрастные линейки — факт контента, а не число в коде: проверяем форму
// упоминания, а не считаем поля дня (у дня нет поля «линейка»).
assert.ok(/5–7, 8–10, 11–13/.test(doc), 'в документе нет трёх возрастных линеек');

console.log('  ok числа программы совпадают с кодом');

/* ---- 2. Проверки: число тестов не выдумано ---- */

// Себя не считаем: иначе число в документе зависит от того, считает ли его тест.
// Считаем все тесты, включая этот: документ говорит про весь прогон, а не про
// «все, кроме проверки документа». Иначе число в документе зависит от того,
// какой тест его проверяет, — и каждый новый тест ломает чужую проверку.
const testFiles = readdirSync(new URL('../scripts/', import.meta.url)).filter(
  (name) => /^test-.*\.tsx?$/.test(name),
);
assert.equal(testFiles.length, 239, `в scripts/ ${testFiles.length} файлов тестов, документ говорит 231`);
assert.ok(doc.includes(String(testFiles.length)), 'число файлов тестов в документе не совпадает');

// Проверок в прогоне — не «одна на файл». Считаем по факту.
let asserts = 0;
for (const name of testFiles) {
  const src = readFileSync(new URL(`../scripts/${name}`, import.meta.url), 'utf8');
  asserts += (src.match(/assert\.[a-z]+\(/g) ?? []).length;
}
// Документ обязан называть фактическое число проверок, а не «много тестов».
assert.ok(
  new RegExp(`${asserts}\\s+(проверок|проверки)`).test(doc) || doc.includes(String(asserts)),
  `проверок в тестах ${asserts}, но в документе это число не названо`,
);
console.log(`  ok файлов тестов ${testFiles.length}, проверок ${asserts}`);

/* ---- 3. Нет обещаний, которых продукт не выполняет ---- */

/**
 * Проверять обещание, а не слово — и уметь читать отрицание.
 *
 * Это четвёртый случай одного класса ошибки в проекте. Проверка на «повысит
 * оценки» падает на фразе «мы **не** обещаем, что программа повысит оценки» —
 * то есть на самом честном месте документа. Поэтому перед каждым совпадением
 * смотрим 80 символов контекста: если там отрицание, это не обещание, а отказ
 * от обещания. Ровно то, что мы хотим видеть.
 */
const promises = [
  { re: /повысит (оценки|успеваемость|IQ)/gi, why: 'обещание роста оценок или IQ' },
  { re: /уровень эмпатии ребёнка (повысится|вырастет)/gi, why: 'обещание уровня эмпатии' },
  { re: /гарантиру\w+ результат/gi, why: 'гарантия результата до сбора данных' },
  { re: /докажет эффективность/gi, why: 'обещание доказать эффективность заранее' },
];
for (const { re, why } of promises) {
  for (const match of doc.matchAll(re)) {
    const before = doc.slice(Math.max(0, (match.index ?? 0) - 200), match.index ?? 0).toLowerCase();
    // Отрицание должно стоять в том же предложении: «мы не обещаем, что
    // программа повысит оценки» — отказ; «в прошлом году продукт повысил
    // оценки, и мы не сомневаемся» — обещание.
    const sentence = before.slice(before.lastIndexOf('.') + 1);
    // `\b` здесь не работает: в JavaScript граница слова считается по ASCII, и
    // для кириллицы «не» не даёт границы ни слева, ни справа. Проверка на `\bне\b`
    // молча проходит мимо отрицания. Поэтому границы задаются через \p{L}.
    const negated = /(^|[^\p{L}])не([^\p{L}]|$)|(^|[^\p{L}])нет([^\p{L}]|$)/iu.test(sentence);
    assert.ok(negated, `в документе обещание без отрицания: ${why} — «${match[0]}»`);
  }
}

// Раздел «Чего мы не обещаем» обязан быть: без него документ превращается в продажу.
assert.ok(/Чего мы не обещаем/.test(doc), 'раздел с честными ограничениями вырезан');
assert.ok(/не обещаем роста IQ/.test(doc), 'не сказано прямо про IQ');
// «Не оценивать социальный выбор» — смысл, а не точная фраза. Проверяем, что
// рядом с «выбор» стоит отрицание оценки, а не подстрочник.
assert.ok(
  /не оценива[а-яё]*[^.]{0,40}(социальн[а-яё]* )?выбор|код не оценивает выбор/i.test(doc),
  'не сказано, что выбор ребёнка не оценивается',
);
assert.ok(/не оцениваем качество выступления/.test(doc), 'не сказано, что качество выступления не оценивается');
console.log('  ok обещаний сверх продукта нет, ограничения названы');

/* ---- 4. Расчёт выборки согласован ---- */

const power = [
  { classes: 2, total: 100, d: '1.03' },
  { classes: 3, total: 150, d: '0.84' },
  { classes: 4, total: 200, d: '0.73' },
  { classes: 5, total: 250, d: '0.65' },
  { classes: 6, total: 300, d: '0.60' },
];
/**
 * Строки таблицы разбираются, а не ищутся регуляркой.
 *
 * Регулярка «5 | 250 | 0.65» не находит строку `| **5** | **250** | **0.65** |`:
 * выделение жирным стоит между разделителями. Разбор по ячейкам снимает
 * разметку и не зависит от того, выделил ли автор нужное число.
 */
const powerRows = doc
  .split('\n')
  .filter((line) => line.startsWith('|'))
  .map((line) => line.split('|').slice(1, -1).map((cell) => cell.replace(/\*\*/g, '').trim()))
  .filter((cells) => cells.length === 3 && /^\d+$/.test(cells[0]) && /^\d+$/.test(cells[1]));

for (const { classes, total, d } of power) {
  const row = powerRows.find((cells) => cells[0] === String(classes));
  assert.ok(row, `в таблице мощности нет строки с ${classes} классами`);
  assert.equal(row?.[1], String(total), `${classes} классов: ${row?.[1]} детей, ожидалось ${total}`);
  assert.equal(row?.[2], d, `${classes} классов: d ${row?.[2]}, ожидалось ${d}`);
  // «Детей всего» — это обе группы вместе, то есть дважды по classes × 25.
  // Первая версия проверки этого не учитывала и падала на собственной ошибке.
  assert.equal(classes * 25 * 2, total, `арифметика не сходится: ${classes} × 25 × 2 ≠ ${total}`);
}
assert.ok(/250 детей · 5 классов/.test(doc) || /250 детей/.test(doc), 'итоговое число детей не названо');
console.log('  ok таблица мощности арифметически сходится');

/* ---- 5. Блокеры названы ---- */

for (const blocker of ['согласия родителей', 'экспертиза контента', 'безопасности', 'Хранение видео']) {
  assert.ok(doc.toLowerCase().includes(blocker.toLowerCase()), `блокер «${blocker}» не назван`);
}
// Документ обязан сказать, что продукт не готов к реальным детям. Проверяем
// смысл («не готов… к работе с детьми»), а не конкретную фразу с «реальными»:
// формулировка в документе может меняться, обещание — нет.
// Порядок слов бывает разный: «не готов к работе с детьми» и «к работе с
// детьми сейчас не готов». Проверка принимает оба, иначе она запрещает
// правильный текст из-за того, что автор поставил слова иначе.
const around = doc.replace(/\n/g, ' ').match(/[^.]{0,120}детьми[^.]{0,120}/gi) ?? [];
assert.ok(
  around.some((fragment) => /не готов[а-яё]*/i.test(fragment)),
  'не сказано, что продукт пока не готов к работе с детьми',
);
console.log('  ok блокеры и текущая неготовность названы');

/* ---- Документ читается глазами: чужие алфавиты и битые символы ---- */

// В первом прогоне в документ попали два иероглифа вместо слова «роль»: набор
// шёл быстро, а проверки на текст не было. Документ, который читает ректор,
// не должен содержать таких мест — они читаются как небрежность всего текста.
const foreign = doc.match(/[\u4e00-\u9fff\u3040-\u30ff\uac00-\ud7af]/g);
assert.equal(foreign, null, `в документе чужие символы: ${foreign?.join(' ')}`);
assert.ok(!/\uFFFD/.test(doc), 'в документе битые символы');
console.log('  ok чужих алфавитов и битых символов нет');

console.log('\nДокумент для ректора: числа сходятся с кодом, обещания не превышают продукт.');
