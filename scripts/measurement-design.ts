/**
 * Расчёт размера выборки для исследования эффекта.
 *
 * Зачем. В `docs/research-measurement-design.md` стоят таблицы: сколько классов
 * нужно, чтобы увидеть эффект d, и сколько видео нужно, чтобы проверить
 * надёжность оценщиков. Числа в документе надо уметь пересчитать: если кто-то
 * поменяет допущения (размер класса, ICC, ожидаемый эффект), таблица должна
 * пересчитаться и расхождение стать видимым, а не остаться в презентации.
 *
 * Что считается:
 *  1. Минимально различимый эффект d для разного числа классов на группу.
 *     Квазиэксперимент с классами, поэтому нужна поправка на кластеризацию:
 *     дисперсия раздувается в 1 + (m - 1)·ICC раз.
 *  2. Сколько двойных видео нужно, чтобы доверительный интервал каппы был
 *     достаточно узким, и сколько всего видео это означает при двойном
 *     кодировании заданной доли.
 *
 * Запуск: npm run measure:design
 *
 * Формулы намеренно простые и явные: это оценка, а не точный расчёт. Точный
 * сделает статистик, когда появятся реальные ICC и разброс по школе.
 */

/** Квантиль стандартного нормального распределения (двусторонняя альфа 0.05). */
const Z_ALPHA = 1.959964;
/** Квантиль для мощности 80%. */
const Z_POWER = 0.841621;

type Design = {
  /** Детей в классе. */
  perCluster: number;
  /** Внутриклассовая корреляция: дети в одном классе похожи. */
  icc: number;
  /** Кластеров на группу. */
  clusters: number;
};

/**
 * Минимально различимый d.
 *
 * При кластеризации эффективный размер выборки на группу — это
 * clusters·perCluster / (1 + (perCluster - 1)·ICC). Дальше обычная формула
 * для двух независимых групп.
 */
function detectableEffect({ perCluster, icc, clusters }: Design): number {
  const inflation = 1 + (perCluster - 1) * icc;
  const effectiveN = (clusters * perCluster) / inflation;
  return (Z_ALPHA + Z_POWER) * Math.sqrt(2 / effectiveN);
}

/**
 * Ширина 95% доверительного интервала каппы Коэна.
 *
 * Оценка через дисперсию: SE ≈ sqrt(p·(1 - p) / (n·(1 - pe)²)), где p —
 * наблюдаемое согласие. Для планирования берём p = 0.85, pe = 0.5 (два
 * уровня, сбалансированные) — умеренно оптимистичный, но не идеальный
 * сценарий. Нам нужен порядок величины, а не третий знак.
 */
function kappaCiHalfWidth(n: number, observed = 0.85, chance = 0.5): number {
  const se = Math.sqrt((observed * (1 - observed)) / (n * (1 - chance) ** 2));
  return Z_ALPHA * se;
}

function fmt(value: number, digits = 2): string {
  return value.toFixed(digits).replace('.', ',');
}

function main() {
  console.log('Размер выборки: сколько классов нужно на группу\n');
  console.log('  класс 25 детей, ICC 0.10, альфа 0.05, мощность 80%\n');
  console.log('  классов  детей/группа  всего детей  различимый d');
  for (const clusters of [2, 3, 4, 5, 6]) {
    const d = detectableEffect({ perCluster: 25, icc: 0.1, clusters });
    console.log(
      `  ${String(clusters).padStart(7)}  ${String(clusters * 25).padStart(12)}  ` +
        `${String(clusters * 50).padStart(11)}  ${fmt(d)}`,
    );
  }

  console.log('\n  Для сравнения: ожидаемый эффект методики по мета-анализу 0.70.');
  const need = [2, 3, 4, 5, 6].find(
    clusters => detectableEffect({ perCluster: 25, icc: 0.1, clusters }) <= 0.7,
  );
  console.log(
    need
      ? `  Значит, чтобы увидеть эффект 0.70, нужно минимум ${need} классов на группу ` +
          `(${need * 50} детей).`
      : '  Ни при 6 классах на группу эффект 0.70 не различим при этих допущениях.',
  );

  console.log('\nЧувствительность к ICC (4 класса на группу, 25 детей в классе)\n');
  console.log('  ICC    различимый d');
  for (const icc of [0.05, 0.1, 0.15, 0.2]) {
    console.log(`  ${fmt(icc)}   ${fmt(detectableEffect({ perCluster: 25, icc, clusters: 4 }))}`);
  }
  console.log(
    '\n  Чем сильнее дети в классе похожи друг на друга, тем хуже: класс — это\n' +
      '  единица анализа, а не ребёнок. Пять классов в одном разбросе значат\n' +
      '  меньше, чем сто детей из ста разных классов.',
  );

  console.log('\nПроверка надёжности: сколько видео нужно двойного кодирования\n');
  console.log('  двойных  полуширина 95% ДИ каппы   всего видео при 25% двойных');
  for (const doubles of [10, 20, 30, 40, 60, 80]) {
    console.log(
      `  ${String(doubles).padStart(7)}  ${fmt(kappaCiHalfWidth(doubles)).padStart(21)}   ` +
        `${String(doubles * 4).padStart(27)}`,
    );
  }
  console.log(
    '\n  Каппа с полушириной больше 0.15 почти ничего не говорит: 0.6 и 0.75\n' +
      '  неразличимы. Отсюда порог: не меньше 40 двойных видео, то есть 160\n' +
      '  видео всего при двойном кодировании четверти.\n' +
      '\n  Это второй неприятный вывод дизайна: проверка надёжности сама\n' +
      '  требует размера выборки. На 20 видео надёжность не проверить — можно\n' +
      '  лишь сказать «оценщики согласились на всех пяти», что ничего не значит.',
  );
}

main();

export {};
