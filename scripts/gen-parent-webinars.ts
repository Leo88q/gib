/**
 * Генератор полной родительской серии вебинаров: 12 тем программы «Гибкость».
 *
 * Зачем: ручной пилот w01 показал формат; 12 текстов вручную — недели. Скрипт
 * собирает каждый вебинар из кода продукта (WEEK_*: parentNote, homeIdeas,
 * weekQuestion, дни и сценарии) + одной честной вставкой: «Три ошибки родителя»
 * — авторский блок по компетенции, помечен как авторский и проверяется методистом.
 * Ничего не выдумывается из внешних источников; цитат и цифр нет вовсе.
 *
 * Запуск: npx tsx scripts/gen-parent-webinars.ts
 * Выход: content/webinars/parent/*.md (12 файлов).
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { PROGRAM, SCENARIO_BY_ID } from '../lib/content/program/index.ts';
import { COMPETENCY_TITLE } from '../lib/year/valued.ts';

const OUT_DIR = join('content', 'webinars', 'parent');
mkdirSync(OUT_DIR, { recursive: true });

const pad = (n: number) => String(n).padStart(2, '0');
const slug = (s: string) => s.toLowerCase().replace(/[^a-zа-яё0-9]+/gi, '-').replace(/(^-|-$)/g, '').slice(0, 48);

const MISTAKES: Record<string, [string, string, string]> = {
  self_awareness: [
    '«Ну сколько можно расстраиваться» — звучит как поддержка, а читается как «твоё чувство неправильное». Ребёнок не перестаёт чувствовать — он перестаёт говорить.',
    'Спрашивать пять раз подряд «что с тобой?!» — пятый вопрос превращает разговор в обыск. Один короткий вопрос и тишина в ответ — нормально.',
    '«Ты смелый, не плачь» — оценка вместо наблюдения. Оценку защищают или опровергают; наблюдение («вижу, тебе больно») принимают.',
  ],
  self_regulation: [
    '«Держи себя в руках!» — приказ вместо навыка. Тело не подчиняется команде; пауза — это тренировка, а не волевое усилие.',
    '«Я сам, только бы быстрее» — взрослая компенсация лишает ребёнка самой практики: он так и не накопит свидетельств «я справляюсь».',
    'Тайм-аут как наказание за эмоцию — ребёнок учится скрывать чувства, а не регулировать их. Передышка нужна ему, а не вам.',
  ],
  empathy: [
    '«Не реви, ему больнее» — соревнование чужих страданий вместо понимания. Вопрос «как ты думаешь, что он чувствует?» работает лучше лозунга.',
    '«Встань на его место» — взрослая абстракция. Дети понимают конкретику: «что бы ты сделал на его месте в этом коридоре?».',
    '«Сам виноват» — приговор до выслушивания. Симпатию нельзя выдать заправочно: сначала «расскажи», потом «что теперь».',
  ],
  relationships: [
    '«Договорились сами — справляйтесь» без правила выхода из конфликта. Детям нужна не «свобода», а простой алгоритм: остановиться, назвать, попросить.',
    '«Делись!» приказом — делиться не заставить, договориться можно: очерёдность, торг, обмен.',
    'Скрывать конфликты при детях — дети перенимают, что спор — это стыдно. Лучше показать ваш собственный «стоп» вслух.',
  ],
  decision_making: [
    '«Выбирай сам» без информации — выбор вслепую не развивает суждения, он развивает случайность. Сначала факты, потом выбор.',
    'Критиковать выбор, который сами предложили сделать, — двойное послание: «я разрешаю, но не принимаю».',
    'Решать за ребёнка, «потому что быстрее». Десять самостоятельных решений за год стоят дороже пяти сэкономленных минут.',
  ],
  growth_mindset: [
    '«У тебя талант» без указания на усилие — похвала-ловушка: пробовать становится страшно. Хвалите стратегию и попытку, не «результат» и не «способность».',
    '«Ты старался, но не вышло» без разбора — старание без анализа учит повторять бесполезное с тем же результатом.',
    'Превращать ошибку в приговор дома — «я всё испортил» слышится в школе следующей же репликой ребёнка.',
  ],
  creative_thinking: [
    '«Придумай что-нибудь!» без материала, времени и темы — запрос вместо среды. Идеи растут на местности, а не в вакууме.',
    'Править «небрежность» вместо сути идеи — критика формы глушит творческий сигнал сильнее любой несправедливости.',
    'Сравнивать с другими детьми — «у Маши лучше» учит соответствовать, а не создавать.',
  ],
};

const files: string[] = [];
for (const week of PROGRAM) {
  const competency = week.competency as string;
  const competencyTitle = COMPETENCY_TITLE[competency as keyof typeof COMPETENCY_TITLE] ?? competency;
  const mistakes = MISTAKES[competency] ?? MISTAKES.self_awareness;
  const days = week.days;

  const storyLines = days.map((day, i) => {
    const scenario = SCENARIO_BY_ID[day.scenarioId];
    const situation = scenario?.variants['5-7'].text ?? '';
    return `День ${day.day} недели — «${day.theme}». Ситуация, с которой сталкивается ребёнок: ${situation} Чему учит этот день: ${day.parentGoal}`;
  });

  const L: string[] = [];
  L.push(`# Вебинар для родителей: неделя ${week.week} «${week.title}»`);
  L.push('');
  L.push(`Компетенция: ${competencyTitle} · возраст 5–13 лет · озвучка — Злата Бабенко · длительность ≈ 13 минут · один спикер.`);
  L.push('');
  L.push('Статус: **сгенерировано** `scripts/gen-parent-webinars.ts` из кода продукта + авторский блок «Три ошибки родителя» (проверяется методистом). Не озвучено, не опубликовано.');
  L.push('');
  L.push('## Текст озвучки');
  L.push('');
  L.push(`Привет. Сегодня говорим про неделю ${week.week} нашей программы — «${week.title}», компетенция: ${competencyTitle.toLowerCase()}. Если вы открыли этот выпуск, скорее всего, с ребёнком уже случилось что-то из списка ниже — или вы хотите, чтобы не случилось. Давайте разберёмся спокойно и по шагам.`);
  L.push('');
  L.push(`Подзаголовок недели: ${week.subtitle}. В основе — навыки ${week.focusSkills.join(' и ')}. Ниже пять дней недели по порядку — ровно то, что ребёнок увидит в приложении, и ровно то, на что стоит опереться вечером.`);
  L.push('');
  L.push('### Пять дней этой недели');
  L.push('');
  L.push(storyLines.join('\n\n'));
  L.push('');
  L.push('### Три ошибки, которые делают даже любящие родители');
  L.push('');
  L.push(`Первая. ${mistakes[0]}`);
  L.push('');
  L.push(`Вторая. ${mistakes[1]}`);
  L.push('');
  L.push(`Третья. ${mistakes[2]}`);
  L.push('');
  L.push('### Что делать дома — три вещи по десять минут');
  L.push('');
  L.push(`Вот три идеи, которые даёт сама программа на эту неделю, и все три занимают не больше десяти минут: ${week.homeIdeas.join(' ')}`);
  L.push('');
  L.push(`Заметка, которую мы написали заранее для этой недели, и с которой я бы начал разговор: ${week.parentNote}`);
  L.push('');
  L.push(`И один вопрос, который можно задать за ужином — ровно один и без оценивания ответа: «${week.weekQuestion}». Слушайте ответ дольше, чем говорите в нём.`);
  L.push('');
  L.push('### Что дальше');
  L.push('');
  L.push(`Если хотите одно действие на всю неделю — откройте со ребёнком день ${days[0].day} во вторник вечером. Десять минут, без оценок и подсказок; рядом — с чаем, не с проверкой. На следующей неделе мы перейдём дальше по программе — темы выстроены так, что каждая опирается на предыдущую.`);
  L.push('');
  L.push('---');
  L.push('');
  L.push('## Источники (для ревью, не в озвучку)');
  L.push('');
  L.push(`- \`lib/content/program/weeks-*\`: неделя ${week.week}, компетенция \`${competency}\`, focusSkills [${week.focusSkills.join(', ')}], дни ${days.map((d) => d.day).join(', ')}.`);
  L.push('- `SCENARIO_BY_ID` (тот же индекс): ситуации дней дословно из варианта 5–7 (названия сюжетов едины, тексты — по линейкам).');
  L.push('- parentNote, homeIdeas, weekQuestion, parentGoal каждого дня — дословно из кода, без редактуры.');
  L.push('- Блок «Три ошибки родителя» — авторский, по компетенции; методист может заменить целиком.');
  L.push('');
  L.push('## Что проверить методисту');
  L.push('');
  L.push('1. Блок ошибок — принимаем, редактируем или заменяем; остальное выведено из кода.');
  L.push('2. Дословность parentNote/homeIdeas/weekQuestion/parentGoal сохранена.');
  L.push('3. Тон — «разговор взрослого со взрослым», без канцелярита; длительность в спокойном темпе ≈ 12–14 минут.');

  const name = `${pad(week.week)}-${slug(week.title)}.md`;
  writeFileSync(join(OUT_DIR, name), L.join('\n') + '\n');
  files.push(name);
}

console.log(`Сгенерировано ${files.length} родительских вебинаров в ${OUT_DIR}`);
