/**
 * Проверка согласованности документов замера.
 *
 * Зачем. Дизайн (`docs/research-measurement-design.md`) и рабочие бланки
 * (`docs/research-measurement-kit.md`) — разные файлы, и они легко разойдутся:
 * добавили признак в бланк, забыли в дизайне; поменяли число отрезков в одном
 * месте, в другом осталось старое. Такое расхождение не ломает сборку и не
 * видно глазом, но означает, что оценщики кодируют не то, что описано в
 * методике.
 *
 * Проверяется:
 *  1. Каждый признак из бланка упомянут в дизайне (по смыслу — по ключевым
 *     словам, а не дословно: документы пишутся для людей, а не для парсера).
 *  2. Все четыре отрезка есть в обоих документах.
 *  3. У каждого признака в бланке есть полные якоря: ни одного «частично»
 *     без описания, все уровни 0..k подписаны словами.
 *  4. Пороги надёжности (каппа, AC1, доля двойного кодирования) совпадают
 *     между дизайном, бланком и скриптом расчёта.
 *  5. В бланках нет наречий оценки в названиях признаков.
 *
 * Запуск: npm run test:measurement
 */

import { readFileSync } from 'node:fs';
import { strict as assert } from 'node:assert';

const read = (path: string) => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8');

// Переводы строк внутри абзаца не должны ломать поиск формулировок: в
// Markdown фраза «замечает ли, что партнёру трудно» легко переносится на две
// строки, и дословный поиск промахивается.
// Маркеры цитат и списков тоже снимаются: фраза может переноситься внутри
// цитаты, и тогда «> » окажется в середине искомой строки. Сравниваем смысл,
// а не разметку.
const normalize = (text: string) =>
  text
    .split('\n')
    .map((line) => line.replace(/^\s*(?:>\s*)+/, ''))
    .join(' ')
    .replace(/\s+/g, ' ');


const design = normalize(read('docs/research-measurement-design.md'));
// Бланк тоже нормализуется: якоря живут в таблице одной строкой, но брифинг
// может переносить их по-другому, и сравнивать надо смысл, а не форматирование.
const kitNormalized = normalize(read('docs/research-measurement-kit.md'));
const kit = read('docs/research-measurement-kit.md');
const script = read('scripts/measurement-design.ts');

/* ---- 1. Признаки бланка есть в дизайне ---- */

/**
 * Соответствие «признак в бланке → как он назван в дизайне». Список явный:
 * документы пишутся для людей, и дословного совпадения формулировок не будет.
 * Если признак добавили только в бланк — он должен появиться и здесь, и в
 * дизайне, иначе проверка ниже не найдёт его в описании отрезков.
 */
const TRAITS: Record<string, string> = {
  'Подошёл к играющим без подсказки': 'подходит или ждёт',
  'Спросил разрешения словами': 'спрашивает разрешения',
  'Взял себе часть игры': 'берёт свою часть',
  'Заметил, что партнёру трудно': 'замечает ли, что партнёру трудно',
  'Пауза перед действием после смены правила': 'пауза перед действием',
  'Переспросил, а не действовал наугад': 'переспрашивает или пробует наугад',
  'Продолжил после смены правила': 'продолжает после смены правила',
  'Вышел показывать': 'выходит или отказывается',
  'Начал показ': 'начинает',
  'Говорил слышно': 'говорит слышно',
  'Что сделал с ошибкой': 'что делает с ошибкой во время показа',
  'Попробовал иначе': 'пробует иначе',
  'Спросил, что делать': 'спрашивает',
  'Назвал, что именно не вышло': 'называет, что именно не вышло',
};

for (const [trait, inDesign] of Object.entries(TRAITS)) {
  assert.ok(kit.includes(`**${trait}**`), `признак «${trait}» есть в карте, но пропал из бланка`);
  assert.ok(
    design.includes(inDesign),
    `признак «${trait}» описан в дизайне как «${inDesign}», но эта формулировка не найдена`,
  );
}
console.log(`  ok ${Object.keys(TRAITS).length} признаков: бланк и дизайн совпадают`);

/* ---- 2. Отрезки ---- */

const SEGMENTS = ['Вход в группу', 'Задание с помехой', 'Показ', 'После ошибки'];
for (const segment of SEGMENTS) {
  assert.ok(kit.includes(segment), `отрезок «${segment}» пропал из бланка`);
  assert.ok(design.includes(segment), `отрезок «${segment}» пропал из дизайна`);
}
assert.ok(
  !/Отрезок 5/.test(kit) && !/Отрезок 5/.test(design),
  'появился пятый отрезок: сначала обоснуйте его в дизайне, потом добавляйте в бланк',
);
console.log('  ok четыре отрезка, ни одного лишнего');

/* ---- 3. Якоря полные ---- */

// Таблицы якорей: шапка начинается с уровня 0, единственная строка описания
// содержит ровно столько ячеек, сколько уровней объявлено в шапке.
const cellsOf = (row: string) => row.split('|').slice(1, -1).map((cell) => cell.trim());
const anchorTables = [...kit.matchAll(/^\| 0 \|[^\n]*\n\|[-| ]+\n(\|[^\n]*\|[ \t]*\n)/gm)];

assert.ok(
  anchorTables.length >= 14,
  `нашлось ${anchorTables.length} таблиц якорей, ожидалось не меньше 14 — признаков без якорей`,
);

for (const table of anchorTables) {
  const header = cellsOf(table[0].split('\n')[0]);
  const body = cellsOf(table[1]);
  assert.equal(
    body.length,
    header.length,
    `в шапке ${header.length} уровней, в описании ${body.length}: «${table[1].trim().slice(0, 60)}»`,
  );
  for (const cell of body) {
    assert.ok(cell.length > 3, `пустой или невнятный якорь: «${cell}»`);
  }
}

// «Частично» как уровень — это не якорь: оценщик не знает, что считать
// половиной. Такое слово допустимо только в тексте, не в ячейке уровня.
assert.ok(
  !/\| частично \|/i.test(kit),
  'уровень «частично» без описания: оценщик не сможет его воспроизвести',
);
console.log('  ok у каждого признака полные якоря, «частично» без описания нет');

/* ---- 4. Пороги совпадают ---- */

for (const threshold of ['0.61', '0.80']) {
  assert.ok(design.includes(threshold), `порог ${threshold} пропал из дизайна`);
}
assert.ok(kit.includes('0.61'), 'порог 0.61 пропал из бланка сводки');
assert.ok(
  script.includes('0.85') || design.includes('40 двойных'),
  'расчёт двойного кодирования разошёлся с дизайном',
);
assert.ok(design.includes('40 двойных'), 'порог «40 двойных видео» пропал из дизайна');
assert.ok(kit.includes('Двойных видео закодировано'), 'в сводке нет поля про двойное кодирование');
console.log('  ok пороги надёжности совпадают в дизайне, бланке и скрипте');

/* ---- 5. Нет наречий оценки ---- */

const JUDGING = ['уверенно', 'правильно', 'хорошо', 'плохо', 'молодец', 'старательно'];
const traitLines = [...kit.matchAll(/^\*\*(.+?)\*\*$/gm)].map((match) => match[1].toLowerCase());
for (const line of traitLines) {
  for (const adverb of JUDGING) {
    assert.ok(
      !line.includes(adverb),
      `название признака «${line}» содержит оценку «${adverb}»: так оценщики расходятся`,
    );
  }
}
console.log('  ok в названиях признаков нет наречий оценки');

/* ---- 6. Документы ссылаются друг на друга ---- */

assert.ok(
  design.includes('research-measurement-kit.md'),
  'дизайн не ссылается на бланки: читатель не найдёт протокол',
);
assert.ok(
  kit.includes('research-measurement-design.md'),
  'бланки не ссылаются на дизайн: непонятно, откуда взялись признаки',
);
console.log('  ok дизайн и бланки ссылаются друг на друга');

/* ---- 7. Брифинг для методиста не разошёлся с дизайном ---- */

const brief = normalize(read('docs/research-methodist-briefing.md'));

// Восемь решений — это повестка встречи. Если в брифинге появилось девятое
// или пропало одно, встреча не влезет в 90 минут и решения будут приняты
// наполовину.
const decisions = [...brief.matchAll(/## Решение (\d+)\./g)].map((match) => Number(match[1]));
assert.deepEqual(
  decisions,
  [1, 2, 3, 4, 5, 6, 7, 8],
  `решения в брифинге идут как ${decisions.join(', ')}, ожидалось 1..8`,
);
console.log('  ok в брифинге ровно восемь решений по порядку');

// Каждое решение должно заканчиваться местом для ответа: брифинг, из которого
// нельзя уйти с записанным ответом, — это ещё один документ, а не встреча.
const answerSlots = (brief.match(/\*\*Решение:\*\*/g) ?? []).length;
assert.ok(
  answerSlots >= 8,
  `мест для записи решения ${answerSlots}, а решений восемь: на встрече некуда писать ответ`,
);

// Якоря, которые обсуждаются на встрече, должны совпадать с бланком: если в
// брифинге уровень описан иначе, методист утвердит не тот протокол.
const anchors = [
  'отказался после двух приглашений',
  'вышел после приглашения',
  'вышел сам, без приглашения',
];
for (const anchor of anchors) {
  assert.ok(
    kitNormalized.toLowerCase().includes(anchor.toLowerCase()),
    `якорь «${anchor}» пропал из бланка`,
  );
  assert.ok(brief.includes(anchor), `якорь «${anchor}» обсуждается на встрече, но не совпадает с бланком`);
}
console.log('  ok спорные якоря в брифинге совпадают с бланком');

// Пороги надёжности и числа выборки на встрече называются те же, что в дизайне.
for (const number of ['0.61', '0.80', '250 детей', '20 детей', '40 двойных']) {
  assert.ok(
    design.includes(number) || kit.includes(number),
    `число «${number}» из брифинга не найдено в дизайне или бланке`,
  );
}
console.log('  ok числа в брифинге взяты из дизайна, а не придуманы заново');

assert.ok(
  brief.includes('research-measurement-design.md') && brief.includes('research-measurement-kit.md'),
  'брифинг не ссылается на оба документа: участники не найдут детали',
);
console.log('  ok брифинг ссылается на дизайн и бланки');

console.log('\nДокументы замера согласованы: 14 признаков, 4 отрезка, 8 решений, пороги на месте.');
