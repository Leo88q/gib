/**
 * Экран педагога: что видно и чего не видно.
 *
 * Тест проверяет экран как текст, а не как набор кнопок. Главное здесь — что
 * экран НЕ показывает: баллов, уровней, ответов детей, отчётов. Если это
 * появится, появится тихо, и никто не заметит.
 *
 * Запуск: npm run test:teacher-cabinet-ui
 */

import { strict as assert } from 'node:assert';
import { renderToStaticMarkup } from 'react-dom/server';
import React, { createElement } from 'react';
import { readFileSync } from 'node:fs';
import TeacherCabinet from '../components/TeacherCabinet';

const raw = readFileSync(new URL('../components/TeacherCabinet.tsx', import.meta.url), 'utf8');

/**
 * Проверяем то, что видит человек, а не комментарии в коде.
 *
 * Здесь легко ошибиться дважды. Сначала — проверкой на подстроку: экран с
 * фразой «это не оценка» падает на слове «оценка». Потом — проверкой исходника:
 * комментарий «баллов здесь нет» падает на слове «балл». Поэтому комментарии
 * вырезаются, и остаётся разметка и тексты.
 */
const source = raw
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .replace(/^\s*\/\/.*$/gm, '');

/* ---- 1. Экран не оценивает ребёнка ---- */

const forbidden = [
  { re: /успеваемост/i, why: 'слово «успеваемость» превращает посещение в оценку' },
  { re: /рейтинг/i, why: 'рейтинг детей не показывается никому' },
  { re: /\bуровень\b/i, why: 'уровень ребёнка педагогу не показывается' },
  { re: /\bбалл/i, why: 'посещение — факт, а не баллы' },
  { re: /процент/i, why: 'процент посещаемости читается как оценка' },
];

for (const { re, why } of forbidden) {
  assert.ok(!re.test(source), `в экране педагога появилось запрещённое: ${why}`);
}
console.log('  ok ни баллов, ни уровней, ни рейтинга, ни процентов');

/* ---- 2. Экран не показывает содержимое ребёнка ---- */

for (const [needle, why] of [
  ['feelings', 'чувства ребёнка педагогу не показываются'],
  ['history', 'истории ребёнка педагогу не показываются'],
  ['report', 'отчёт родителю педагогу не показывается'],
  ['reflection', 'рефлексия ребёнка педагогу не показывается'],
] as const) {
  assert.ok(!new RegExp(needle, 'i').test(source), `экран тянет лишнее: ${why}`);
}
console.log('  ok экран не обращается к чувствам, историям и отчётам');

/* ---- 3. Согласие: код, а не добавление по идентификатору ---- */

assert.ok(source.includes('Код для родителей'), 'код группы не показан педагогу — его некому назвать');
assert.ok(
  /Назовите код родителям/.test(source),
  'нет объяснения, что ребёнок попадает в группу только после ввода кода',
);
console.log('  ok ребёнок попадает в группу по коду, а не по идентификатору');

/* ---- 4. Отметка — одна кнопка на ребёнка ---- */

assert.ok(source.includes('Был') && source.includes('Не был'), 'нет кнопок отметки');
assert.ok(!/Комментарий|Причина|Почему не был/.test(source), 'экран собирает причину отсутствия');
console.log('  ok отметка в один клик, причины отсутствия нет');

/* ---- 5. Сбой загрузки не выглядит как пустая группа ---- */

assert.ok(
  /Не удалось загрузить группу/.test(source),
  'сбой загрузки не отличается от «детей нет»: педагог не заметит, что связи нет',
);
console.log('  ok сбой загрузки отличается от пустой группы');

/* ---- 6. Запрет объявлен и педагогу ---- */

assert.ok(
  /Ответы детей/.test(source) && /так и задумано/.test(source),
  'педагогу не сказано, что он не видит ответы детей: он будет искать их и звонить родителям',
);
console.log('  ok педагогу прямо сказано, чего он не видит');

/* ---- 7. Компонент рендерится ---- */

// В Next.js JSX не требует React в области видимости, а при запуске через tsx
// (сборка CJS) требует. Кладём его в глобальную область до рендера.
Object.assign(globalThis, { React });

const html = renderToStaticMarkup(createElement(TeacherCabinet));
assert.ok(html.includes('Моя группа'), 'экран без заголовка');
assert.ok(!html.includes('NaN'), 'в разметке NaN');
console.log('  ok компонент рендерится без данных и без NaN');

console.log('\nЭкран педагога: посещаемость группы, без содержимого ребёнка.');
