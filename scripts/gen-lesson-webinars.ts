const coachFor = (title: string): string[] => {
  for (const prefix of Object.keys(blockCoaching)) {
    if (title.startsWith(prefix)) return blockCoaching[prefix];
  }
  return genericCoaching;
};

const cumulative = (blocks: MeetingBlock[]): string[] => {
  let t = 0;
  return blocks.map((b) => {
    const from = `${Math.floor(t / 60)}:${String(t % 60).padStart(2, '0')}`;
    t += b.minutes * 60;
    const to = `${Math.floor(t / 60)}:${String(t % 60).padStart(2, '0')}`;
    return `${from}–${to}`;
  });
};

