export function questForTask(taskId: string, fallback: string): string {
  return TASK_QUESTS[taskId] ?? `Лис просит: ${fallback.toLowerCase()}`;
}

export function questForScenario(competency: string): string {
  return (
    SCENARIO_QUESTS[competency as CompetencyId] ??
    'Лис столкнулся с ситуацией. Выбери, что сделать.'
  );
}

export function pick(list: string[], seed: number): string {
  return list[Math.abs(seed) % list.length];
}
