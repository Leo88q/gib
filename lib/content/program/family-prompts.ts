/**
 * Родительские тексты тем 4–12: подзаголовок, заметка, идеи для дома, вопрос.
 *
 * Почему отдельным файлом. Раньше недели 4–12 получали один общий набор в
 * `program/index.ts`: три одинаковые идеи для дома и один вопрос на девять тем.
 * Так сделали, чтобы убрать из старых текстов обещания результата, — и вместе
 * с обещаниями убрали смысл: к четвёртой неделе взрослый читал одно и то же
 * каждую неделю, а блок «практика в парах» в плане встречи повторялся дословно
 * 27 раз из 36.
 *
 * Что здесь вместо этого. По три идеи и один вопрос на каждую тему — про то,
 * что действительно происходит на этой неделе. Условия те же, что были у
 * общего текста: всё добровольно, ребёнок может отказаться, оценок нет, ничего
 * не обещается. Тексты адресованы взрослому и говорят о ребёнке в третьем лице:
 * их нельзя читать детям на встрече (это проверяет `test:year-meeting`).
 *
 * Почему не подставляется автоматически. Недели 1–3 остаются со своими
 * текстами: они уже написаны под свои темы, и переписывать работающее ради
 * единообразия незачем.
 */

