export type OptionQuality = 'good' | 'partial' | 'bad';

export type ScenarioOption = {
  text: string;
  /**
   * Устаревшая метка оценки ответа. В новом контенте её нет: история не
   * оценивает социальный выбор ребёнка, а равную награду дают и за пропуск.
   *
   * Поле остаётся только для чтения старых снимков и квитанций: удалить его
   * из старых записей можно лишь миграцией, а новые записи его не создают.
   */
  quality?: OptionQuality;
  note: string;
};

export type ScenarioVariant = {
  title: string;
  text: string;
  options: ScenarioOption[];
  /** Optional frozen Ink program for newly created story-choice sessions. */
  ink?: { version: 1; json: string };
  /** Optional frozen two-decision Ink tree; old snapshots remain single-choice. */
  deepInk?: { version: 1; json: string };
};

export type Scenario = {
  id: string;
  competency: CompetencyId;
  skillLabel: string;
  variants: Record<AgeBand, ScenarioVariant>;
  /** Связка с когнитивным заданием: тренируем навык «в действии». */
  practiceTaskId: string;
  practiceWhy: string;
  /** Микро-задание на дом (одно предложение родителю). */
  home: string;
  /** Строка в отчёте родителю. */
  report: string;
  /** Зона роста. */
  growth: string;
  /** Вопрос семье за ужином. */
  question: string;
};

