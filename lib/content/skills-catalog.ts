export const SKILL_BY_ID: Record<string, SkillDefinition> = Object.fromEntries(
  SKILLS_CATALOG.map(skill => [skill.id, skill]),
);

export function skillsForCompetency(competency: CompetencyId): SkillDefinition[] {
  return SKILLS_CATALOG.filter(skill => skill.competency === competency);
}

/** Навык для показа ребёнку в его возрастной линейке. */
export function skillLabelForChild(skillId: string, band: AgeBand): string | undefined {
  return SKILL_BY_ID[skillId]?.child[band];
}
