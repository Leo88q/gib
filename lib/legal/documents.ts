/**
 * Юридические документы: политика, оферта, возврат, согласие.
 *
 * Почему тексты лежат в коде, а не в CMS. Их должно быть видно в репозитории и
 * в диффе: изменение политики — событие, а не правка в чужой админке. Кроме
 * того, версия документа связана с записью о согласии: если версии разойдутся,
 * согласие станет недействительным молча, и это никто не заметит.
 *
 * Чего эти тексты не делают. Они не заменяют юриста. Здесь описаны факты о
 * продукте на русском языке: какие данные, зачем, сколько хранятся, как
 * удалить, как вернуть деньги. Реквизиты оператора вынесены в `OPERATOR` и
 * намеренно оставлены незаполненными: продукт не должен делать вид, что
 * документ готов, пока в нём нет названия и адреса того, кто отвечает.
 * Проверка `legalReady()` возвращает false, пока они пустые, и это видно и в
 * проверке готовности, и на странице документов.
 */

export const PRIVACY_VERSION = '2026-11-03';
export const OFFER_VERSION = '2026-11-03';

export type Operator = {
  /** Название ИП или ООО. Пустая строка — не заполнено. */
  name: string;
  /** ИНН или ОГРН. */
  registration: string;
  /** Адрес для обращений по данным. */
  address: string;
  /** Почта для обращений по данным ребёнка и по возвратам. */
  email: string;
};

/**
 * Реквизиты оператора. Заполняются при регистрации; пустые значения —
 * осознанное «не заполнено», а не забывчивость. Каждое поле проверяется
 * `legalReady()`, и незаполненное видно в чек-листе запуска.
 */
export const OPERATOR: Operator = {
  name: '',
  registration: '',
  address: '',
  email: '',
};

/**
 * Реквизиты с учётом переменных окружения деплоя (`GIB_OPERATOR_*`).
 * По умолчанию возвращает `OPERATOR`, чтобы незаполненные реквизиты оставались
 * явным блокером запуска до внесения настоящих данных ИП или ООО.
 */
export function resolveOperator(env: Record<string, string | undefined> = process.env): Operator {
  return {
    name: env.GIB_OPERATOR_NAME?.trim() || OPERATOR.name,
    registration: env.GIB_OPERATOR_REGISTRATION?.trim() || OPERATOR.registration,
    address: env.GIB_OPERATOR_ADDRESS?.trim() || OPERATOR.address,
    email: env.GIB_OPERATOR_EMAIL?.trim() || OPERATOR.email,
  };
}

/** Готовы ли реквизиты. Без них документы не могут считаться опубликованными. */
export function legalReady(operator: Operator = OPERATOR): boolean {
  return Boolean(operator.name.trim() && operator.registration.trim() && operator.address.trim() && /^[^@\s]+@[^@\s]+\.[^@\s]{2,}$/.test(operator.email));
}

/** Что осталось заполнить: список для чек-листа, а не общая фраза «не готово». */
export function legalMissing(operator: Operator = OPERATOR): string[] {
  const missing: string[] = [];
  if (!operator.name.trim()) missing.push('название оператора (ИП или ООО)');
  if (!operator.registration.trim()) missing.push('ИНН или ОГРН');
  if (!operator.address.trim()) missing.push('адрес для обращений');
  if (!operator.email.trim()) missing.push('почта для обращений по данным');
  return missing;
}

