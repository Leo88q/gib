import type { GuardianConsent } from '../types.ts';

/**
 * Согласие законного представителя: единственный юридический минимум, который
 * можно проверить кодом.
 *
 * Что здесь есть и чего нет. Здесь — версия текста, дата и правило «без
 * согласия ребёнок не занимается». Здесь нет и не может быть самого согласия:
 * его даёт взрослый, а политику и основания обработки проверяет юрист. Код
 * гарантирует только то, что продукт не начнёт занятие, если записи о согласии
 * нет, и что выданное согласие не подменяется молча новой редакцией.
 *
 * Уже существующие профили (созданные до запуска) согласия не имеют. Это
 * намеренно: считать их согласными нельзя, а требовать переподписания при
 * первом входе — можно, и именно так и поступает интерфейс.
 */

/** Версия текста, которую видит взрослый. Меняется при изменении политики. */
export const CONSENT_VERSION = '2026-11-03';

/** Человекочитаемая дата вступления редакции в силу. */
export const CONSENT_DATE = '3 ноября 2026 года';

/**
 * Что взрослый подтверждает. Формулировки — не юридический текст, а его
 * пересказ на экране; юридический текст живёт в `/legal/privacy` и
 * `/legal/terms`. Пересказ не должен обещать больше, чем делает продукт.
 */
export const CONSENT_POINTS: readonly string[] = [
  'Я родитель или законный представитель ребёнка и могу дать согласие за него.',
  'Я прочитал(а), какие данные о ребёнке хранятся: имя или ник, возраст, ответы в историях, отметки о занятиях.',
  'Я понимаю, что приложение предлагает варианты для обсуждения, а не оценивает ребёнка.',
  'Я знаю, что данные можно выгрузить или удалить в любой момент, и как это сделать.',
];

/** Самая длинная фраза согласия: используется в проверках интерфейса. */
export function consentSummary(): string {
  return `Согласие законного представителя, редакция от ${CONSENT_DATE}.`;
}

/** Запись о согласии для нового профиля. Время ставит сервер. */
export function newConsent(now = Date.now()): GuardianConsent {
  return { version: CONSENT_VERSION, at: now };
}

/** Есть ли действующая запись о согласии у профиля. */
export function hasConsent(profile: { guardianConsent?: GuardianConsent }): boolean {
  const value = profile.guardianConsent;
  return !!value && typeof value.version === 'string' && value.version.length > 0
    && Number.isFinite(value.at) && value.at > 0;
}

/**
 * Устарело ли согласие.
 *
 * Согласие выдано на конкретную редакцию текста. Когда редакция меняется,
 * старая запись остаётся действительной ровно до момента, когда продукт
 * начинает работать по новым правилам, — поэтому функция возвращает true и
 * интерфейс просит подтвердить заново. Неизвестная версия тоже считается
 * устаревшей: лучше переспросить, чем принять согласие на текст, которого мы
 * не можем показать.
 */
export function consentOutdated(profile: { guardianConsent?: GuardianConsent }): boolean {
  if (!hasConsent(profile)) return true;
  return profile.guardianConsent!.version !== CONSENT_VERSION;
}
