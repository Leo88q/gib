/** Одна ситуация из жизни, где навык виден. */
export type LifeExample = {
  /** Где это происходит: короткий контекст, чтобы узнавалось. */
  where: string;
  /** Что именно делает ребёнок. */
  what: string;
};

export type LessonPage = {
  lesson: number;
  unit: number;
  title: string;
  /** Что тренировали — одна фраза без терминов. */
  trained: string;
  /** Три ситуации из жизни. */
  examples: LifeExample[];
  /** Одно наблюдение на неделю для родителя. */
  noticeAtHome: string;
  /** Результат по ФГОС — для учителя. */
  fgosWording: string;
};

