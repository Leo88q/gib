/** Главная компетенция занятия: первая из списка. */
function mainCompetency(lesson: Lesson): CompetencyId {
  return competenciesOfLesson(lesson)[0] ?? weekByNumber(lesson.unit).competency;
}

/**
 * Страница занятия.
 *
 * Результат по ФГОС берётся из той же разметки, что отдаётся школе: одна
 * формулировка, два адресата.
 */
export function lessonPage(lesson: Lesson, fgosWording: string): LessonPage {
  const competency = mainCompetency(lesson);

  // Названия сцен — чтобы страница говорила о конкретном занятии, а не была
  // одинаковой для всей темы.
  const scenes = lesson.dayIndexes
    .map((index) => PROGRAM_DAYS[index])
    .filter(Boolean)
    .map((entry) => SCENARIO_BY_ID[entry.day.scenarioId]?.variants['8-10'].title)
    .filter(Boolean);

  return {
    lesson: lesson.number,
    unit: lesson.unit,
    title: lesson.title,
    trained: TRAINED[competency],
    // Ситуации для главной компетенции; если сцен в занятии несколько, третья
    // ситуация берётся из второй компетенции — так страница отражает занятие,
    // а не только его тему.
    examples: [...(LIFE_EXAMPLES[competency] ?? [])].slice(0, scenes.length > 2 ? 3 : 2),
    noticeAtHome: NOTICE_AT_HOME[competency],
    fgosWording,
  };
}
