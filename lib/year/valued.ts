/**
 * Страница занятия: что тренировали и как это видно в жизни.
 *
 * Зачем это нужно. Педагог провёл 40 минут и не может ответить на вопрос
 * «а что вы там делаете?» так, чтобы это поняли родитель и завуч. Родитель
 * видит отчёт «прошли сцену про поделку» — это описание действия, а не ценности.
 *
 * Откуда идея. Из курса Drama Teacher Academy «Soft Skills, The Tangible Value of
 * the Drama Curriculum»: задача не в том, чтобы объявить навыки, а в том, чтобы
 * сделать их **осязаемыми** — показать, где именно в жизни они видны.
 *
 * Что здесь есть:
 *  - что тренировали (одна фраза, без профессиональных терминов);
 *  - как это видно в жизни (три конкретные ситуации, не «станет эмпатичнее»);
 *  - что заметить дома (одно наблюдение на неделю, не задание);
 *  - результат по ФГОС (для учителя и завуча, одной строкой).
 *
 * Чего здесь нет:
 *  - обещаний результата («ребёнок научится…»);
 *  - оценок и уровней;
 *  - домашних заданий как обязанности. «Заметить» — не «выполнить».
 */

import type { CompetencyId } from '../types.ts';
