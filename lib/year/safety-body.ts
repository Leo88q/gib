/** Все правила одним списком: для страницы педагога и для печати. */
export const ALL_SAFETY_RULES: readonly SafetyRule[] = [...TOUCH_RULES, ...BODY_RULES, ...GROUP_RULES];

/** Правило по id: страница занятия ссылается на правила, а не пересказывает их. */
export const SAFETY_BY_ID: Readonly<Record<string, SafetyRule>> = Object.fromEntries(
  ALL_SAFETY_RULES.map((rule) => [rule.id, rule]),
);

/**
 * Проверки, которые нужны на конкретной теме, или пустой список.
 *
 * Пустой список — не «всё безопасно», а «телесных упражнений в этой теме нет».
 * Разницу важно не потерять: педагог должен видеть, что проверять нечего.
 */
export function safetyForUnit(unit: number): SafetyCheck | undefined {
  const entry = BODY_UNITS.find((item) => item.unit === unit);
  if (!entry) return undefined;
  return {
    what: entry.what,
    rules: entry.rules.map((id) => SAFETY_BY_ID[id]).filter(Boolean),
  };
}
