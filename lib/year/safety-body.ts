/**
 * Безопасность телесных упражнений: то, чего в программе нет.
 *
 * Зачем отдельный файл. Программа закрывает эмоциональную безопасность подробно:
 * «право на пас», «тяжёлые личные истории не разыгрываются», обратная связь по
 * модели «Вижу — Нравится — Предлагаю». А упражнений, где дети водят друг друга
 * за плечи, сжимают кулаки и «выпускают пар», там нет ни одного правила. Это не
 * придирка: взрослый, ведущий «Поводыря» без правил, делает ровно то, за что
 * программа обещает безопасность.
 *
 * Откуда логика. Не из документа, а из того, что уже сказано в продукте про
 * эмоции: ребёнок всегда может отказаться, и отказ не наказывается. В телесном
 * упражнении у этого правила есть три части, которых нет у разговора:
 * прикосновение, остановка на середине и «ведущий на человека».
 *
 * Чего здесь нет и не будет:
 *  - медицинских слов и оценок «тревожный ребёнок»;
 *  - требования выполнять упражнение «для пользы»;
 *  - упражнений на доверие с закрытыми глазами как обязательных: только по
 *    желанию и только с открытым взглядом по умолчанию.
 *
 * Правило одно и короткое: **согласие спрашивают каждый раз, а не один раз**.
 * Согласие на занятие не равно согласию на прикосновение.
 */

/** Что делать и почему. Один пункт — одно действие. */
