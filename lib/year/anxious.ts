/**
 * Готовая подсказка педагогу по последней отметке.
 *
 * Возвращает три вещи: что за ребёнок (без ярлыков), какой приём применить и
 * чего не говорить. Именно это показывается в кабинете — не список всех шести
 * приёмов, а один, уместный сейчас.
 */
export function hintFor(level: 0 | 1 | 2 | undefined, refusalsInRow = 0): {
  headline: string;
  technique: Technique;
  avoid: PhraseToAvoid;
  needsTalk: boolean;
} {
  if (refusalsInRow >= 3) {
    return {
      headline: 'Три показа подряд без выхода: нужен разговор, а не уговоры',
      technique: ANXIOUS_TECHNIQUES[1],
      avoid: PHRASES_TO_AVOID[1],
      needsTalk: true,
    };
  }
  if (level === undefined) {
    return {
      headline: 'Ещё не выходил: первый показ — вдвоём или из-за ширмы',
      technique: ANXIOUS_TECHNIQUES[5],
      avoid: PHRASES_TO_AVOID[0],
      needsTalk: false,
    };
  }
  if (level === 0) {
    return {
      headline: 'Отказался: снизить ставку, не уговаривать',
      technique: ANXIOUS_TECHNIQUES[0],
      avoid: PHRASES_TO_AVOID[3],
      needsTalk: false,
    };
  }
  if (level === 1) {
    return {
      headline: 'Вышел по приглашению: убрать слова, оставить паузу',
      technique: ANXIOUS_TECHNIQUES[3],
      avoid: PHRASES_TO_AVOID[4],
      needsTalk: false,
    };
  }
  return {
    headline: 'Вышел сам: не вмешиваться',
    technique: ANXIOUS_TECHNIQUES[3],
    avoid: PHRASES_TO_AVOID[5],
    needsTalk: false,
  };
}
