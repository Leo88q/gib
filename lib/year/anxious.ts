/**
 * Приёмы для ребёнка, которому страшно выходить.
 *
 * Зачем отдельный файл. Лестница (`stage.ts`) говорит, *с какой ступени* начинать.
 * Этот файл говорит, *что именно сказать и сделать*, когда ребёнок уже стоит у
 * края и не идёт. Тут же лежит главный риск: взрослый, желая помочь, говорит
 * ровно то, что закрывает выход.
 *
 * Чего здесь нет и не будет:
 *  - слов «терапия», «коррекция», «диагноз», «тревожность» как ярлыка ребёнка;
 *  - советов родителю обратиться к специалисту (это не наша роль и не наш тон);
 *  - упражнений на дыхание «чтобы успокоиться» — они превращают показ в
 *    процедуру и к тому же принудительны;
 *  - любых формулировок, которые оценивают ребёнка.
 *
 * Принцип один: **сначала снижаем ставку, потом просим**. Не наоборот.
 */

/** Приём: что делать и почему работает. */
