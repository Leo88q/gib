/**
 * Лестница выхода на публику: что делать между «отказался» и «вышел сам».
 *
 * Зачем это нужно. Продукт умеет фиксировать факт: отказался (0), вышел после
 * приглашения (1), вышел сам (2). Но факт без следующего шага бесполезен.
 * Ребёнок, отказавшийся на трёх показах подряд, не выбывает из группы — он
 * остаётся в ней и перестаёт быть участником. Педагог видит «0, 0, 0» и не
 * знает, что делать в четверг.
 *
 * Откуда взята логика. Из практики Social Theatre (Shawn Amador, LCSW,
 * Jessica Kingsley 2018, 2023): движение идёт ступенями от снижения ставки к
 * самостоятельному выходу, и начинается оно не с уговоров, а с задач, где
 * смотреть на тебя не страшно.
 *
 *   ступень 0 → 1: снизить ставку (клоунада, роль без слов, выход вдвоём)
 *   ступень 1 → 2: убрать приглашение (пауза, взгляд, «кто хочет»)
 *
 * Важное ограничение. Это не терапия и не коррекция. Ни одного медицинского
 * слова здесь нет и быть не может: продукт не диагностирует и не лечит.
 * Лестница — методический инструмент для педагога в обычной группе.
 *
 * Ещё одно ограничение, и оно не обсуждается: **отказ никогда не наказывается и
 * не отменяет участия**. Ребёнок, который смотрит, — участник. Если лестница
 * превратится в давление («ты уже большой»), ребёнок перестанет доверять
 * взрослому, и методика сломается надёжнее, чем от отсутствия ступеней.
 */

import type { ShowcaseLevel } from './lessons.ts';

/**
 * Ступень, на которой стоит ребёнок.
 *
 * Номер — не оценка и не ранг: это подсказка педагогу, с чего начинать
 * следующую встречу. Ребёнок на ступени 0 не «хуже» ребёнка на ступени 3.
 */
export type StageStep = {
  /** 0..3, где 3 — вышел сам. */
  step: 0 | 1 | 2 | 3;
  /** Название для педагога: короткое, чтобы читалось с листа. */
  title: string;
  /** Что делать на следующей встрече. Одно действие, а не программа. */
  next: string;
  /** Чего делать нельзя: самое частое и самое вредное. */
  avoid: string;
};

/**
 * Лестница. Четыре ступени — потому что между «отказался» и «вышел сам» есть
 * два разных состояния, и они требуют разных действий:
 *
 *  - на 0 ребёнку страшно смотреть, как другие выходят;
 *  - на 1 он выходит, но только когда позовут;
 *  - на 2 он выходит сам, но с оглядкой;
 *  - на 3 приглашение не нужно.
 */
export const STAGE_LADDER: readonly StageStep[] = [
  {
    step: 0,
    title: 'Смотрит, но не выходит',
    next: 'Дай роль без слов и без выхода вперёд: держать ширму, подавать реквизит, быть «светом». Он в сцене, но на него не смотрят.',
    avoid: 'Не уговаривать и не сравнивать с другими. «Все вышли, а ты?» закрывает выход надолго.',
  },
  {
    step: 1,
    title: 'Выходит вдвоём',
    next: 'Поставь его в пару с тем, кому он доверяет, и выйдите вместе. Ставка ниже: если страшно, страшно не только ему.',
    avoid: 'Не выставлять вперёд одного, пока он держится за партнёра. Партнёр — не костыль, а условие.',
  },
  {
    step: 2,
    title: 'Выходит по приглашению',
    next: 'Перестань приглашать словами. Пауза, взгляд, открытая ладонь — и тишина. Приглашение без слов оставляет выбор ему.',
    avoid: 'Не хвалить за выход громче, чем за отказ. Иначе выход становится платой за похвалу, а не его решением.',
  },
  {
    step: 3,
    title: 'Выходит сам',
    next: 'Ничего не делай. Не комментируй, не подбадривай, просто дай место. Вмешательство возвращает его на ступень ниже.',
    avoid: 'Не превращать в «пример для других». Ответственность за чужие показы — не его работа.',
  },
];

/**
 * С какой ступени начинать, зная историю показов ребёнка.
 *
 * Берётся последняя отметка, а не средняя: ребёнок мог отказаться один раз в
 * начале года и с тех пор выходить сам. Средняя превратила бы его в «того, кто
 * иногда отказывается» — это оценка, а не факт.
 *
 * Если отметок не было, возвращается ступень 0 с другим смыслом: не «отказался»,
 * а «ещё не выходил». Педагогу это важно различать.
 */
export function stageFor(lastLevel: ShowcaseLevel | undefined): StageStep {
  if (lastLevel === undefined) {
    return {
      step: 0,
      title: 'Ещё не выходил',
      next: 'Первый показ всегда вдвоём или из-за ширмы. Не ждать, что выйдет один: первый выход — не проверка, а знакомство.',
      avoid: 'Не начинать с одиночного выхода и не спрашивать «готов?» — на этот вопрос честный ответ «нет».',
    };
  }
  // 0 → ступень 0, 1 → ступень 2, 2 → ступень 3: шкала показа не совпадает с
  // лестницей, потому что между «вышел после приглашения» стоит «вышел вдвоём».
  const map: Record<ShowcaseLevel, 0 | 2 | 3> = { 0: 0, 1: 2, 2: 3 };
  const step = map[lastLevel];
  return STAGE_LADDER[step];
}

/**
 * Сколько отказов подряд — это уже сигнал, а не случайность.
 *
 * Зачем число. Один отказ — норма: ребёнок не выспался, поссорился, стесняется
 * новой группы. Три подряд — это уже паттерн, и он требует разговора с
 * родителем и смены подхода. Без порога педагог либо тревожится из-за одного
 * отказа, либо не замечает третьего.
 *
 * Порог не «диагноз» и нигде не показывается ребёнку.
 */
export const REFUSAL_ALERT = 3;

/**
 * Сколько отказов подряд накопилось к концу расписания.
 *
 * Считается по отметкам показов от последнего к первому: как только встречается
 * выход, счёт останавливается. Пропущенные показы (нет отметки) не считаются
 * ни отказом, ни выходом: ребёнка могло не быть, и это не то же самое.
 */
export function refusalsInRow(levels: readonly (ShowcaseLevel | undefined)[]): number {
  let count = 0;
  for (let i = levels.length - 1; i >= 0; i -= 1) {
    const level = levels[i];
    if (level === undefined) continue;
    if (level === 0) count += 1;
    else break;
  }
  return count;
}
