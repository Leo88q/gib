/**
 * Видео-демонстрации для педагога: что показать, а не рассказать.
 *
 * Зачем это нужно. У педагога есть план на 40 минут, но план — текст. Текст
 * отвечает на вопрос «что делать», и не отвечает на «как это выглядит». Пока
 * человек не увидел, как ведут круг двадцать детей, он будет вести его
 * неправильно: либо слишком быстро, либо начиная с вопросов, на которые никто
 * не ответит.
 *
 * Откуда идея. Drama Notebook (Janea Dahl) продаёт подписку на 1 500 сценариев,
 * и её главный аргумент — «fifty games on video that help you teach drama like
 * an expert overnight». Не библиотека, а видео. Это самая дешёвая вещь из всего
 * разбора конкурентов и самая нужная.
 *
 * Что здесь есть и чего нет. Здесь — **сценарий съёмки**: для каждого ролика
 * написано, что в кадре, что говорит педагог, сколько длится и что должно быть
 * видно. Самих видео нет: их снимают на телефон, один раз, и они живут годами.
 * Обещать «видео есть» в продукте, где их нет, нельзя.
 *
 * Почему 12, а не 50. У Drama Notebook 50 роликов про 400 игр. У нас 36 занятий
 * с пятью блоками, и повторяются одни и те же ситуации. Двенадцать закрывают
 * всё, что педагог делает впервые.
 */

/** Где пригодится ролик: номер блока в плане встречи. */
export type DemoBlock = 'circle' | 'debrief' | 'training' | 'pair' | 'closing' | 'showcase' | 'trouble';

export type Demo = {
  /** Идентификатор: по нему ролик ищется в интерфейсе. */
  id: string;
  /** Название для педагога. */
  title: string;
  /** Блок занятия. */
  block: DemoBlock;
  /** Длительность в секундах: короткие ролики смотрят, длинные откладывают. */
  seconds: number;
  /** Что в кадре — буквально, чтобы можно было снять без режиссёра. */
  shot: string;
  /** Что говорит педагог — прямая речь, её можно использовать как есть. */
  says: string;
  /** Что должно быть видно на экране: критерий, что ролик снят правильно. */
  mustSee: string;
};

