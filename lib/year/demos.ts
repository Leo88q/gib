/**
 * Ролики для блока плана встречи.
 *
 * Педагог не смотрит все двенадцать сразу: он готовится к конкретному блоку и
 * видит те два-три ролика, которые нужны к четвергу.
 */
export function demosForBlock(block: DemoBlock): Demo[] {
  return DEMOS.filter((demo) => demo.block === block);
}

/**
 * Общая длительность всех роликов: это то, что человек реально посмотрит.
 *
 * Считается, а не заявляется: если сумма выйдет за полчаса, педагог не станет
 * смотреть это перед занятием, и набор надо сокращать.
 */
export function totalSeconds(): number {
  return DEMOS.reduce((sum, demo) => sum + demo.seconds, 0);
}
