/**
 * Что предложить педагогу в конкретной ситуации.
 *
 * Возвращается не весь список, а два упражнения: педагог в стрессе выбирает из
 * двух, а не из восемнадцати.
 */
export function backupFor(situation: BackupSituation, count = 2): BackupExercise[] {
  return BACKUP_EXERCISES.filter((exercise) => exercise.situation === situation).slice(0, count);
}
