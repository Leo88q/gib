/**
 * Запасной набор: что делать, если группа не готова к плану.
 *
 * Зачем это нужно. План встречи рассчитан на группу, которая пришла и может
 * играть. В реальности бывает иначе: половины детей нет, все после контрольной,
 * двое поссорились, в кабинете идёт ремонт. Педагог с одним планом в этой
 * ситуации либо проваливает план, либо импровизирует. Импровизация без опоры —
 * это «поиграем в что-нибудь», то есть потеря занятия.
 *
 * Откуда идея. Drama Notebook (Janea Dahl) продаёт библиотеку из 400+ игр именно
 * поэтому: учителю нужен запас. Нам не нужно 400: нужно 20, разложенных по
 * ситуации, и у каждого должно быть понятно, когда его доставать.
 *
 * Правило, которое здесь важнее списка: **запасное упражнение не отменяет
 * занятие**. Оно сохраняет форму (круг, этюд, итог), а не заменяет её игрой.
 */

/** Ситуация, в которой нужен запас. */
