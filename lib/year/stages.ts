/**
 * Какой этап у занятия.
 *
 * Считается от числа занятий в году, а не от номеров 1/18/36: если год когда-то
 * станет другим, этапы останутся на своих местах — начало, середина, конец.
 * Первое и последнее занятие — вход и итог, среднее — середина.
 */
export function stageOfLesson(lesson: Lesson, totalLessons: number): YearStage {
  if (totalLessons <= 2) return lesson.number === 1 ? 'opening' : 'closing';
  if (lesson.number <= 1) return 'opening';
  if (lesson.number >= totalLessons) return 'closing';
  const middle = Math.ceil(totalLessons / 2);
  if (lesson.number === middle) return 'middle';
  return 'middle';
}

/**
 * Этап по номеру занятия, без объекта занятия.
 *
 * Нужен там, где есть только номер (отчёт, страница родителя), а строить Lesson
 * ради одного поля — лишняя работа и лишний источник расхождений.
 */
export function stageOfNumber(number: number, totalLessons: number): YearStage {
  if (totalLessons <= 2) return number <= 1 ? 'opening' : 'closing';
  if (number <= 1) return 'opening';
  if (number >= totalLessons) return 'closing';
  return 'middle';
}

/**
 * Строка этапа для отчёта родителю.
 *
 * Не «этап 2 из 3» и не «прогресс 60%»: проценты от года ничего не значат для
 * ребёнка, а выглядят как оценка. Здесь — что происходит и один вопрос.
 */
export function stageNote(stage: YearStage): string {
  const info = STAGE_INFO[stage];
  return `${info.title}. ${info.task}`;
}
