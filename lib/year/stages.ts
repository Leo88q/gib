/**
 * Этапы года: вход, три четверти, итог.
 *
 * Зачем отдельный файл. Год из тридцати шести занятий выглядит ровным, но
 * нагрузка в нём распределена неравномерно: первые занятия года — это знакомство
 * и первый замер, последние — сводка всего, что было. Если спрашивать у ребёнка и
 * родителя одно и то же в сентябре и в мае, то первый замер покажет разницу в
 * формулировке, а не в ребёнке.
 *
 * Откуда взято. Из программы, раздел 8: «входная (занятие 1), промежуточная
 * (занятие 24), итоговая (занятие 48)». В нашей сетке из 36 занятий те же три
 * точки приходятся на занятия 1, 18 и 36 — начало, середина и конец.
 *
 * Чего здесь нет и не будет:
 *  - слова «диагностика»: это педагогическое наблюдение и разговор, не оценка;
 *  - числовых норм и порогов: «правильного» ответа на вопрос этапа не бывает;
 *  - сравнения детей между собой: этап один для всей группы, ступени у всех разные.
 *
 * Три точки, а не две. Две точки («до» и «после») не отличают рост навыка от
 * того, что ребёнок просто стал на год старше. Средний замер это хотя бы
 * разделяет по времени.
 */

import type { Lesson } from '../content/year/types.ts';

/** Этап года. Четыре значения — потому что «середина» бывает двух видов. */
export type YearStage = 'opening' | 'middle' | 'closing';

export type StageInfo = {
  id: YearStage;
  /** Название для педагога: короткое, читается с листа. */
  title: string;
  /** Что делает педагог на этой неделе — одно действие. */
  task: string;
  /** Вопрос круга, который задают и детям, и дома родителю. */
  question: string;
  /** Чего на этом этапе не делают. */
  avoid: string;
};

