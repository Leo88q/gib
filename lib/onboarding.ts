import type { HouseholdAdult } from './types.ts';

/**
 * Два вопроса, которые продукт не задавал, а без них текст обращается не туда.
 *
 * Первый — кто ведёт встречу. Год построен как 36 встреч по 40 минут с
 * планом, и план написан для того, кто ведёт: говорит, делит на пары,
 * останавливает сцену. У педагога на это есть роль и кабинет, у родителя —
 * ничего. Пока ответа нет, продукт продаёт родителю подписку и ни слова не
 * говорит о том, что раз в неделю ему предстоит вести занятие.
 *
 * Второй — есть ли дома взрослый, к которому ребёнок может обратиться.
 * Формулировки практики местами говорят «попросите знакомого взрослого». Это
 * совет по безопасности, и убирать его нельзя; но взрослому, который ведёт
 * занятие, полезно знать, кому этот совет адресован на самом деле.
 *
 * Оба ответа — самоотчёт одного аккаунта. Это не проверка личности и не роль
 * доступа: профиль по-прежнему принадлежит одному взрослому.
 */

export type MeetingLead = 'adult' | 'child';

export type OnboardingAnswers = {
  meetingLead: MeetingLead;
  householdAdult: HouseholdAdult;
};

