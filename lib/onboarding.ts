/**
 * Что обещает продукт при этом ответе.
 *
 * Одна строка на экране «что вы покупаете»: взрослый получает план встречи,
 * ребёнок — короткие шаги. Разница не в цене, а в том, что именно доступно.
 */
export function meetingLeadSummary(lead: MeetingLead): string {
  return lead === 'adult'
    ? 'Раз в неделю взрослый ведёт встречу 40 минут по готовому плану: 36 встреч за год, 12 из них — показ.'
    : 'Ребёнок занимается короткими шагами по 10–15 минут; встречи с планом доступны, но не обязательны.';
}

/** Заголовок для плана встречи: кто его держит в руках. */
export function meetingLeadTitle(lead: MeetingLead | undefined): string {
  return lead === 'adult' ? 'План встречи для взрослого' : 'План встречи';
}

/**
 * К кому обращаться в тексте практики, когда нужен взрослый.
 *
 * Возвращает null для «дома такого взрослого нет»: в этом случае нельзя
 * подставлять «родителя», которого в семье нет. Остальные тексты остаются
 * как есть — совет по безопасности не переписывается.
 */
export function trustedAdultLabel(value: HouseholdAdult | undefined): string | null {
  if (value === 'other') return 'знакомый взрослый, которому доверяет семья';
  if (value === 'none') return null;
  return 'родитель или законный представитель';
}

/** Строка для плана встречи: что взрослый должен знать о семье до занятия. */
export function householdNote(value: HouseholdAdult | undefined): string {
  if (value === 'none') return 'Дома взрослого, к которому можно обратиться, нет. Все обращения «к взрослому» в практике адресованы вам.';
  if (value === 'other') return 'Дома есть другой взрослый. Уточните до занятия, к кому ребёнку можно идти за поддержкой, и назовите его группе.';
  if (value === 'parent') return 'Ребёнок называет вас тем взрослым, к которому обращается. Задания «попросите взрослого» — про вас.';
  return 'Взрослый в семье не уточнён: формулировки «обратиться к взрослому» относите к себе.';
}

/** Проверка ответа, пришедшего с клиента. */
export function parseOnboardingAnswers(value: unknown): OnboardingAnswers | null {
  if (!value || typeof value !== 'object' || Array.isArray(value)) return null;
  const record = value as Record<string, unknown>;
  const lead = record.meetingLead;
  const adult = record.householdAdult;
  if (lead !== 'adult' && lead !== 'child') return null;
  if (adult !== 'parent' && adult !== 'other' && adult !== 'none') return null;
  return { meetingLead: lead, householdAdult: adult };
}
